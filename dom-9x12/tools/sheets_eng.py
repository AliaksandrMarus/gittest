def gcolor(g):
    return ORANGE if g in (1, 2) else (RED if g in (7, 8, 12) else BLUE)


ROT = {"s": 0, "n": 180, "e": -90, "w": 90}


def device(sh, X, Y, kind, side, col):
    """Условное обозначение в локальных координатах: +y — в помещение."""
    def g(inner):
        rot = f" rotate({ROT[side]})" if side else ""
        sh.add(f'<g transform="translate({f(X)} {f(Y)}){rot}" stroke="{col}" fill="none" '
               f'stroke-width="0.25">{inner}</g>')
    if kind in ("L", "L44"):
        fill = col if kind == "L44" else "#fff"
        g(f'<circle r="1.5" fill="{fill}" fill-opacity="{0.25 if kind == "L44" else 1}"/>'
          f'<path d="M-1.06 -1.06 L1.06 1.06 M-1.06 1.06 L1.06 -1.06"/>')
    elif kind == "LW":
        g(f'<path d="M-1.5 0 A1.5 1.5 0 0 0 1.5 0 Z" fill="{col}" fill-opacity="0.3"/>')
    elif kind == "FAN":
        g('<circle r="1.4" fill="#fff"/><path d="M-0.8 0.6 L-0.8 -0.6 L0 0.2 L0.8 -0.6 L0.8 0.6"/>')
    elif kind in ("SW1", "SW2"):
        t = '<path d="M1.7 2.9 L2.3 2.3"/>' + ('<path d="M1.25 3.35 L1.85 2.75"/>' if kind == "SW2" else "")
        g(f'<circle cy="1.0" r="0.75" fill="#fff"/><path d="M0.5 1.5 L2.0 3.0"/>{t}')
    elif kind in ("S", "S2", "S44", "S54"):
        wet = kind in ("S44", "S54")
        stems = '<path d="M0 1.3 L0 2.2 M-0.8 2.2 L0.8 2.2"/>' if kind != "S2" else \
            '<path d="M-0.5 1.2 L-0.5 2.2 M0.5 1.2 L0.5 2.2 M-1 2.2 L1 2.2"/>'
        g(f'<path d="M-1.3 0.15 A1.3 1.3 0 0 0 1.3 0.15 Z" fill="{col if wet else "#fff"}" '
          f'fill-opacity="{0.35 if wet else 1}"/>{stems}')
    elif kind in ("OUT", "OUT3"):
        g(f'<rect x="-0.9" y="0.2" width="1.8" height="1.8" fill="#fff"/><circle cy="1.1" r="0.3" fill="{col}"/>')
        if kind == "OUT3":
            sh.text(X + 2.6, Y - 1.4, "3ф", 1.4, c=col)
    elif kind == "ShchR":
        g(f'<rect x="-2.4" y="0" width="4.8" height="1.8" fill="#fff"/>'
          f'<path d="M-2.4 1.8 L2.4 0 L2.4 1.8 Z" fill="{col}"/>')


