def breaker(sh, x, y0, y1, rcd=False, col="#000"):
    """Вертикальный автомат: линия y0→y1, контакт с ножом и крестиком; АВДТ — с овалом и узлом УЗО."""
    a = y0 + (y1 - y0) * 0.35
    b = y0 + (y1 - y0) * 0.65
    sh.line(x, y0, x, a, 0.3, c=col)
    sh.line(x, b, x, y1, 0.3, c=col)
    sh.line(x, b, x - 2.2, a + 0.6, 0.3, c=col)
    sh.line(x - 0.7, a - 0.7, x + 0.7, a + 0.7, 0.3, c=col)
    sh.line(x - 0.7, a + 0.7, x + 0.7, a - 0.7, 0.3, c=col)
    if rcd:
        m = (a + b) / 2
        sh.add(f'<ellipse cx="{f(x - 0.9)}" cy="{f(m)}" rx="2.4" ry="1.0" stroke="{col}" '
               f'stroke-width="0.25" fill="none"/>')
        sh.line(x - 3.3, m, x - 5, m, 0.25, c=col, dash="0.6 0.4")
        sh.rect(x - 6.6, m - 0.8, 1.6, 1.6, sw=0.25, c=col)


def _wrap_words(c, n):
    out, cur = [], ""
    for wd in c.split():
        if len(cur) + len(wd) + 1 > n and cur:
            out.append(cur)
            cur = wd
        else:
            cur = f"{cur} {wd}".strip()
    out.append(cur)
    return out


